//! A component exercising private workers through ordinary prompt calls.

#[cfg(target_arch = "wasm32")]
mod component {
    #[expect(
        clippy::same_length_and_capacity,
        clippy::collection_is_never_read,
        reason = "generated by wit-bindgen"
    )]
    mod bindings {
        wit_bindgen::generate!({
            path: ["../../wit", "wit"],
            world: "fleet:test-worker/plugin@0.0.0",
            generate_all,
        });
    }

    use bindings::{
        exports::fleet::providers::{prompts, worker},
        fleet::providers::{
            types::{ContentBlock, Prompt, PromptContext, PromptOutput, PromptResponse},
            workers::{self, Connection, Listener},
        },
    };
    use futures_util::future;
    use wit_bindgen::{StreamReader, StreamResult};

    struct Component;

    async fn read(mut data: StreamReader<u8>) -> Vec<u8> {
        let mut bytes = Vec::new();
        loop {
            let (status, chunk) = data.read(Vec::with_capacity(16 * 1024)).await;
            bytes.extend(chunk);
            if matches!(status, StreamResult::Dropped) {
                return bytes;
            }
        }
    }

    impl prompts::Guest for Component {
        fn get(_name: String) -> impl Future<Output = Result<Option<Prompt>, String>> {
            future::ready(Ok(None))
        }

        async fn render(context: PromptContext, input: String) -> Result<PromptResponse, String> {
            let connection =
                workers::connect(context.prompt.name, context.prompt.config.into_bytes()).await?;
            let output = connection.read()?;
            let (mut writer, reader) = bindings::wit_stream::new();
            let written = connection.write(reader)?;
            let ((), bytes) = future::try_join(
                async move {
                    let remaining = writer.write_all(input.into_bytes()).await;
                    drop(writer);
                    if !remaining.is_empty() {
                        return Err("request stream closed".into());
                    }
                    written.await
                },
                async move {
                    let bytes = read(output.data).await;
                    output.result.await?;
                    Ok(bytes)
                },
            )
            .await?;
            Ok(PromptResponse {
                output: vec![PromptOutput::Assistant(vec![ContentBlock::Text(
                    String::from_utf8(bytes).map_err(|error| error.to_string())?,
                )])],
            })
        }
    }

    async fn echo(connection: Connection, count: u32) -> Result<(), String> {
        let input = connection.read()?;
        let (mut writer, reader) = bindings::wit_stream::new();
        let written = connection.write(reader)?;
        future::try_join(
            async move {
                let prefix = format!("{count}:").into_bytes();
                if !writer.write_all(prefix).await.is_empty() {
                    return Err("reply stream closed".into());
                }
                let mut data = input.data;
                loop {
                    let (status, chunk) = data.read(Vec::with_capacity(16 * 1024)).await;
                    if !writer.write_all(chunk).await.is_empty() {
                        return Err("reply stream closed".into());
                    }
                    if matches!(status, StreamResult::Dropped) {
                        break;
                    }
                }
                input.result.await?;
                drop(writer);
                Ok(())
            },
            async { written.await },
        )
        .await?;
        Ok(())
    }

    impl worker::Guest for Component {
        async fn run(initialization: Vec<u8>, incoming: Listener) -> Result<(), String> {
            if initialization == b"{\"fail\":true}" {
                return Err("fixture startup failure".into());
            }
            if initialization == b"{\"spin\":true}" {
                #[expect(clippy::infinite_loop, reason = "exercises forced worker shutdown")]
                loop {
                    core::hint::spin_loop();
                }
            }
            if workers::connect("nested".into(), Vec::new()).await.is_ok() {
                return Err("worker unexpectedly started another worker".into());
            }
            let mut count = 0_u32;
            while let Some(connection) = incoming.accept().await {
                count = count.saturating_add(1);
                drop(wit_bindgen::spawn_local(async move {
                    drop(echo(connection, count).await);
                }));
            }
            Ok(())
        }
    }

    bindings::export!(Component with_types_in bindings);
}
